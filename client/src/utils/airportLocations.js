const locationLookup = new Map();
AIRPORT_LOCATIONS.forEach(({ city, code, aliases }) => {
  [city, code, ...aliases].forEach((name) => locationLookup.set(name.trim().toLocaleLowerCase(), code));
});

export const resolveAirportCode = (value) => {
  const normalized = value.trim();
  if (/^[a-z]{3}$/i.test(normalized)) return normalized.toUpperCase();
  return locationLookup.get(normalized.toLocaleLowerCase()) || null;
};
